/**
 * @param {string} country
 * @param {string} [city]
 * @returns {{ lat: number, lon: number, capitalFallback: boolean, placeLabel: string } | null}
 */
export function resolveLocalityCoords(country, city = '') {
  const cc = String(country || '').trim().toUpperCase();
  if (!cc) return null;
  const cityName = String(city || '').trim();
  if (cityName) {
    const hit = STATS_CITY_COORDS[`${cc}|${cityName.toLowerCase()}`];
    if (hit) {
      return {
        lat: hit.lat,
        lon: hit.lon,
        capitalFallback: false,
        placeLabel: cityName,
      };
    }
  }
  const cap = STATS_CAPITALS[cc];
  if (!cap) return null;
  return {
    lat: cap.lat,
    lon: cap.lon,
    capitalFallback: true,
    placeLabel: cityName || cap.name,
  };
}
