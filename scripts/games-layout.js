/**
 * Game groups come from the folder tree: games/<group>/<game>/registration.js.
 * Games in one group share games/<group>/data (word sets) and games/<group>/shared (their loader).
 *
 * Browsers and bundles cannot list folders, so this writes app/games-layout.js from the scan.
 * Run by build, dev, and each game's Vite config; `node scripts/games-layout.js` refreshes it by hand.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GAMES = path.join(ROOT, 'games');
const LAYOUT_FILE = path.join(ROOT, 'app/games-layout.js');
const REGISTRY_FILE = path.join(ROOT, 'app/game-registry.js');
const GROUP_RE = /^g\d+$/;

/** @returns {Record<string, string[]>} group → game ids */
export function scanGameGroups() {
  /** @type {Record<string, string[]>} */
  const groups = {};
  const groupNames = fs
    .readdirSync(GAMES, { withFileTypes: true })
    .filter((e) => e.isDirectory() && GROUP_RE.test(e.name))
    .map((e) => e.name)
    .sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));
  const seen = new Map();
  for (const group of groupNames) {
    const ids = fs
      .readdirSync(path.join(GAMES, group), { withFileTypes: true })
      .filter((e) => e.isDirectory() && fs.existsSync(path.join(GAMES, group, e.name, 'registration.js')))
      .map((e) => e.name)
      .sort();
    for (const id of ids) {
      if (seen.has(id)) throw new Error(`Game "${id}" is in both ${seen.get(id)} and ${group}`);
      seen.set(id, group);
    }
    if (ids.length) groups[group] = ids;
  }
  return groups;
}

/** Every game folder must be imported by app/game-registry.js (it sets the home screen order). */
function checkRegistry(groups) {
  const text = fs.readFileSync(REGISTRY_FILE, 'utf8');
  const listed = new Set([...text.matchAll(/'\.\.\/games\/(g\d+\/[^/']+)\/registration\.js'/g)].map((m) => m[1]));
  const onDisk = new Set(Object.entries(groups).flatMap(([g, ids]) => ids.map((id) => `${g}/${id}`)));
  const missing = [...onDisk].filter((p) => !listed.has(p));
  const stale = [...listed].filter((p) => !onDisk.has(p));
  if (missing.length || stale.length) {
    throw new Error(
      `app/game-registry.js is out of sync with games/:` +
        (missing.length ? ` add ${missing.join(', ')};` : '') +
        (stale.length ? ` remove ${stale.join(', ')};` : '')
    );
  }
}

export function writeGamesLayout() {
  const groups = scanGameGroups();
  checkRegistry(groups);
  const body =
    `/** Generated by scripts/games-layout.js from games/<group>/<game>/ — do not edit. */\n` +
    `export const GAME_GROUPS = ${JSON.stringify(groups, null, 2).replace(/"/g, "'")};\n`;
  const prev = fs.existsSync(LAYOUT_FILE) ? fs.readFileSync(LAYOUT_FILE, 'utf8') : '';
  if (prev !== body) fs.writeFileSync(LAYOUT_FILE, body);
  return groups;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(JSON.stringify(writeGamesLayout(), null, 2));
}
