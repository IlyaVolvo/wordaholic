/**
 * Embed ADMIN_PASSWORD (SHA-256 hex) into TransWord admin password-config.js.
 * Static hosts have no runtime secrets — hash is baked into the published admin gate.
 *
 * Usage:
 *   ADMIN_PASSWORD=<sha256-hex> node scripts/embed-admin-password.js [outDir]
 *   node scripts/hash-admin-password.js 'my-secret'   # print hex for the env var
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const DEFAULT_HASH =
  '3c9ff67ab650bc854b145c690b52efc42ed356151a181513b64f2e799e24ec5f'; // sha256('sobaka12')

function isSha256Hex(value) {
  return typeof value === 'string' && /^[a-f0-9]{64}$/i.test(value.trim());
}

/**
 * @param {string} [outRoot] destination root (default: repo games/transword/admin)
 */
export function embedAdminPassword(outRoot = path.join(ROOT, 'games/transword/admin')) {
  const raw = (process.env.ADMIN_PASSWORD || '').trim();
  let hash = DEFAULT_HASH;
  let source = 'default';

  if (raw) {
    if (!isSha256Hex(raw)) {
      throw new Error(
        'ADMIN_PASSWORD must be a 64-char SHA-256 hex digest (hashed password), not plaintext. ' +
          "Generate with: node scripts/hash-admin-password.js 'your-password'"
      );
    }
    hash = raw.toLowerCase();
    source = 'env';
  } else {
    console.warn(
      'ADMIN_PASSWORD unset — using default local hash (password: sobaka12). ' +
        'Set ADMIN_PASSWORD to a SHA-256 hex for production.'
    );
  }

  ensureDir(outRoot);
  const file = path.join(outRoot, 'password-config.js');
  const body = `/**
 * Auto-generated by scripts/embed-admin-password.js — do not edit by hand.
 * Source: ${source}
 */
export const ADMIN_PASSWORD_HASH = '${hash}';
export const ADMIN_PASSWORD_SOURCE = '${source}';
`;
  fs.writeFileSync(file, body);

  const gateFile = path.join(outRoot, 'gate.js');
  if (fs.existsSync(gateFile)) {
    const gate = fs.readFileSync(gateFile, 'utf8').replace(
      /const WH_ADMIN_PASSWORD_HASH = '[a-f0-9]{64}';/,
      `const WH_ADMIN_PASSWORD_HASH = '${hash}';`
    );
    fs.writeFileSync(gateFile, gate);
  }

  return { file, source };
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = process.argv[2]
    ? path.resolve(process.argv[2])
    : path.join(ROOT, 'games/transword/admin');
  const result = embedAdminPassword(out);
  console.log(`Wrote ${result.file} (source=${result.source})`);
}
